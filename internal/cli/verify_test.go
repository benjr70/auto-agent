// verdicts is the fake Verify Step answering, its MCP servers connected. A
// verdict with no ID answers the item at its place in the answer.
func verdicts(shots []verifier.Shot, vs ...verifier.Verdict) steptest.Reply {
	return verdictsVia(nil, shots, vs...)
}

func verdictsVia(servers []string, shots []verifier.Shot, vs ...verifier.Verdict) steptest.Reply {
	connected := []map[string]string{}
	for _, name := range servers {
		connected = append(connected, map[string]string{"name": name, "status": "connected"})
	}
	init, _ := json.Marshal(map[string]any{
		"type": "system", "subtype": "init", "session_id": "verify-1", "model": "claude-opus", "permissionMode": "dontAsk",
		"tools": append([]string{"StructuredOutput"}, verifier.Spec().Tools...), "slash_commands": []string{"factory:" + verifier.Name},
		"mcp_servers": connected,
	})
	items := append([]verifier.Verdict{}, vs...)
	for i := range items {
		if items[i].ID == 0 {
			items[i].ID = i + 1
		}
	}
	return steptest.Reply{Lines: []string{string(init), steptest.Success(verifier.Result{Items: items, Tour: append([]verifier.Shot{}, shots...)})}}
}

func passes(text string) verifier.Verdict {
	return verifier.Verdict{Text: text, Verdict: "PASS", Class: verifier.Local, Evidence: []string{"`./greet` printed hello"}}
}

const (
	sayHello  = "the greeting says hello"
	litPanel  = "the greeting is lit on the panel"
	reachProd = "the greeting reaches prod <!-- post-deploy: curl -s https://prod/greeting -->"
	loud      = "the greeting is loud"
)

// checklistBody is an Agent PR's description with these unticked items.
func checklistBody(items ...string) string {
	var b strings.Builder
	b.WriteString("## Summary\n\nAdds the greeting.\n\n## Acceptance criteria\n\n- [ ] not a verification item\n\n## Manual verification\n\n")
	for _, item := range items {
		b.WriteString("- [ ] " + item + "\n")
	}
	b.WriteString("\n---\n\nGenerated by `auto-agent`\n")
	return b.String()
}

// reviewedPR is PR #55 open, reviewed, its CI green and no round yet: the
// reconcile Lane's reason incomplete, with these items to verify.
func (f *fireFixture) reviewedPR(items ...string) {
	f.listOurPR()
	f.pr.comments = []string{finding.Done(0, 0, "abc", finding.Routes{}, "")}
	f.pr.body = checklistBody(items...)
}

// verifyInput is what the Verify Step was sent.
func (f *fireFixture) verifyInput(t *testing.T) verifier.Input {
	t.Helper()
	calls := f.verifier.Calls()
	if len(calls) == 0 {
		t.Fatal("the Verify Step was not called")
	}
	var input verifier.Input
	stdin := calls[len(calls)-1].Stdin
	if at := strings.Index(stdin, "{"); at < 0 || json.Unmarshal([]byte(stdin[at:]), &input) != nil {
		t.Fatalf("the Verify Step was sent %s", stdin)
	}
	return input
}

// verifyOf is the Verification round in a Fire record.
func verifyOf(record map[string]any) map[string]any {
	v, _ := record["verify"].(map[string]any)
	return v
}

// The Verification round, Go's, with a Verify Step: the checklist, the
// environment booted from the PR head, the boxes, the tour and the one
// evidence comment.
func TestFireVerify(t *testing.T) {
	t.Run("a passing item is ticked and the ticket is done (behaviour 1)", func(t *testing.T) {
		f := newFireFixture(t, labelsConfig)
		f.reviewedPR(sayHello)
		f.verifier.Script(verdicts(nil, passes(sayHello)))
		f.mustFire(0)
		if !strings.Contains(f.pr.body, "- [x] "+sayHello+"\n") || !strings.Contains(f.pr.body, "- [ ] not a verification item") {
			t.Errorf("the body is\n%s", f.pr.body)
		}
		round := f.pr.comments[len(f.pr.comments)-1]
		for _, want := range []string{"### Manual verification — round 1/3\n", "**Result: 1/1 PASS, 0 deferred, 0 FAIL.**", "#### 1. " + sayHello + " — PASS (local)\n\n- `./greet` printed hello\n"} {
			if !strings.Contains(round, want) {
				t.Errorf("the round's comment lacks %q:\n%s", want, round)
			}
		}
		record := f.record()
		v := verifyOf(record)
		if f.labelled() != "AFK:done" || v["done"] != true || v["line"] != "manual-verify: 1/1 PASS, 0 deferred, 0 FAIL" || record["phase"] != "done" {
			t.Errorf("labels %q, record %v", f.labelled(), record)
		}
		// The environment of PR #55, booted from its head, torn down after.
		if calls := strings.Join(f.provider.Calls(), "|"); calls != "down --all|down --all|up --pr 55|down --pr 55" {
			t.Errorf("the provider was called %s", calls)
		}
		input := f.verifyInput(t)
		if len(input.Items) != 1 || input.Items[0].Text != sayHello || strings.Join(input.Block, ",") != "WEB_URL=http://127.0.0.1:9/" || input.PR != 55 || input.Issue.Number != 20 {
			t.Errorf("the Step was told %+v", input)
		}
		if info, err := os.Stat(input.EvidenceDir); err != nil || !info.IsDir() || !strings.HasPrefix(input.EvidenceDir, filepath.Join(f.state, "verify", "pr-55")+"/") || v["dir"] != input.EvidenceDir {
			t.Errorf("the evidence directory %q: %v", input.EvidenceDir, err)
		}
	})
	t.Run("only passes are ticked: a justified deferral stays unticked, an unjustified one is a FAIL", func(t *testing.T) {
		f := newFireFixture(t, labelsConfig)
		f.reviewedPR(sayHello, litPanel, reachProd, loud)
		f.verifier.Script(verdicts(nil, passes(sayHello),
			verifier.Verdict{Text: litPanel, Verdict: "DEFER", Class: verifier.Hardware, Evidence: []string{}, Blocker: "the panel must be attached"},
			verifier.Verdict{Text: reachProd, Verdict: "DEFER", Class: verifier.DeployedEnv, Evidence: []string{}, SpecDemanded: "GET https://prod/greeting gives 200 and hello"},
			verifier.Verdict{Text: loud, Verdict: "DEFER", Class: verifier.Local, Evidence: []string{"no time"}}))
		f.fixer.Script(disputes("the ticket never asks for a loud greeting"))
		f.mustFire(0)
		for _, want := range []string{"- [x] " + sayHello, "- [ ] " + litPanel, "- [ ] " + reachProd, "- [ ] " + loud} {
			if !strings.Contains(f.pr.body, want+"\n") {
				t.Errorf("the body lacks %q:\n%s", want, f.pr.body)
			}
		}
		round := f.pr.comments[len(f.pr.comments)-1]
		for _, want := range []string{"**Result: 1/4 PASS, 2 deferred, 1 FAIL.**", "— DEFER (hardware)", "- **Deferred:** needs hardware: the panel must be attached",
			"- **Deferred:** needs a deployed environment; post-deploy check demanded: GET https://prod/greeting gives 200 and hello", "- **Post-deploy spec:** `curl -s https://prod/greeting`",
			"#### 4. " + loud + " — FAIL (unjustified)"} {
			if !strings.Contains(round, want) {
				t.Errorf("the round's comment lacks %q:\n%s", want, round)
			}
		}
		// A FAIL leaves the ticket as it was: here its Fix disputes, and the
		// PR is parked with the round its one evidence.
		if f.labelled() != "" || verifyOf(f.record())["done"] != false {
			t.Errorf("labels %q, record %v", f.labelled(), f.record())
		}
		if strings.Count(strings.Join(f.pr.comments, "\n"), "### Manual verification") != 1 {
			t.Errorf("more than one comment for the round: %v", f.pr.comments)
		}
	})
	t.Run("all items passed or justifiably deferred: AFK:done, the lock released", func(t *testing.T) {
		f := newFireFixture(t, labelsConfig)
		f.reviewedPR(sayHello, litPanel)
		f.verifier.Script(verdicts(nil, passes(sayHello), verifier.Verdict{Text: litPanel, Verdict: "DEFER", Class: verifier.Hardware, Evidence: []string{}, Blocker: "the panel must be attached"}))
		f.mustFire(0)
		writes := f.writes()
		if f.labelled() != "AFK:done" || !strings.HasSuffix(writes, "POST "+reviewedPath+"\nPOST "+lockPath+"\nDELETE "+unlockPath) {
			t.Errorf("labels %q, GitHub received\n%s", f.labelled(), writes)
		}
	})
	t.Run("the provider writes its temporary files under the round's directory, gone after down", func(t *testing.T) {
		f := newFireFixture(t, labelsConfig)
		f.reviewedPR(sayHello)
		seen := filepath.Join(f.out, "tmpdir")
		f.provider.Script(providertest.Script{
			Up:   []providertest.Reply{{Stdout: "WEB_URL=http://127.0.0.1:9/\n", Run: fmt.Sprintf(`echo "$TMPDIR" > '%s'; echo x > "$TMPDIR/compose.yml"`, seen)}},
			Down: []providertest.Reply{{Run: fmt.Sprintf(`ls "$TMPDIR" > '%s.down'`, seen)}},
		})
		f.verifier.Script(verdicts(nil, passes(sayHello)))
		f.mustFire(0)
		tmp, _ := os.ReadFile(seen)
		atDown, _ := os.ReadFile(seen + ".down")
		dir := f.verifyInput(t).EvidenceDir
		if got := strings.TrimSpace(string(tmp)); got != filepath.Join(dir, "tmp") || strings.TrimSpace(string(atDown)) != "compose.yml" {
			t.Errorf("up's TMPDIR was %q, want %s; down saw %q in it", got, filepath.Join(dir, "tmp"), atDown)
		}
		if _, err := os.Stat(filepath.Join(dir, "tmp")); !os.IsNotExist(err) {
			t.Errorf("the round's tmp directory is still there: %v", err)
		}
		// The Verify Step's TMPDIR is under the State dir too, gone with it.
		if step := f.verifier.Calls()[0].Env["TMPDIR"]; !strings.HasPrefix(step, filepath.Join(f.state, "tmp")+"/") {
			t.Errorf("the Verify Step ran with TMPDIR %q", step)
		}
	})
	t.Run("a failed boot posts an infrastructure error and no verdicts (behaviour 2)", func(t *testing.T) {
		f := newFireFixture(t, labelsConfig)
		f.reviewedPR(sayHello)
		f.provider.Script(providertest.Script{Up: []providertest.Reply{{Exit: 4, Stderr: "compose: the db did not start"}}})
		f.mustFire(0)
		if len(f.verifier.Calls()) != 0 {
			t.Error("a Verify Step was run on an environment that did not boot")
		}
		round := f.pr.comments[len(f.pr.comments)-1]
		if !strings.Contains(round, "### Manual verification — round 1/3: infrastructure error") || !strings.Contains(round, "compose: the db did not start") || strings.Contains(round, "PASS") || strings.Contains(round, "FAIL") {
			t.Errorf("the round's comment is\n%s", round)
		}
		// A round whose environment never booted leaves no evidence directory,
		// and its comment names none.
		if strings.Contains(round, "Evidence directory:") {
			t.Errorf("the infra round's comment names an evidence directory:\n%s", round)
		}
		if left, _ := filepath.Glob(filepath.Join(f.state, "verify", "*", "*")); len(left) != 0 {
			t.Errorf("the infra round left %v", left)
		}
		v := verifyOf(f.record())
		if !strings.Contains(f.pr.body, "- [ ] "+sayHello) || f.labelled() != "" || v["infra"] == "" || !strings.HasPrefix(v["line"].(string), "manual-verify: infra-error — ") || f.record()["exit"] != 0.0 {
			t.Errorf("labels %q, record %v", f.labelled(), f.record())
		}
		// The Sweep's down --all, down --all before, the one retry with a
		// down between, and down after.
		if calls := strings.Join(f.provider.Calls(), "|"); calls != "down --all|down --all|up --pr 55|down --pr 55|up --pr 55|down --pr 55" {
			t.Errorf("the provider was called %s", calls)
		}
		// The PR has its round: the next Fire only sweeps, and does not boot
		// it again.
		f.mustFire(0)
		if len(f.provider.Calls()) != 7 || f.provider.Calls()[6] != "down --all" {
			t.Errorf("the provider was called again: %v", f.provider.Calls())
		}
	})
	t.Run("teardown runs when the Step fails (behaviour 3)", func(t *testing.T) {
		f := newFireFixture(t, labelsConfig)
		f.reviewedPR(sayHello)
		f.verifier.Script(crashes)
		f.mustFire(1)
		if calls := f.provider.Calls(); len(calls) != 4 || calls[3] != "down --pr 55" {
			t.Errorf("the provider was called %v", calls)
		}
		// No verdict was invented, and the attempt is counted.
		if state.IsVerifyRound(f.pr.comments[len(f.pr.comments)-1]) || strings.Contains(f.pr.body, "[x]") || len(f.comments) != 1 || !strings.Contains(f.record()["error"].(string), "the verify Step ended FAILED") {
			t.Errorf("comments %v, ticket comments %+v, record %v", f.pr.comments, f.comments, f.record())
		}
	})
	t.Run("an answer that leaves an item out is corrected once, then counted", func(t *testing.T) {
		f := newFireFixture(t, labelsConfig)
		f.reviewedPR(sayHello, loud)
		f.verifier.Script(verdicts(nil, passes(sayHello)), verdicts(nil, passes(sayHello), passes(loud)))
		f.mustFire(0)
		if calls := f.verifier.Calls(); len(calls) != 2 || !strings.Contains(f.pr.body, "- [x] "+loud) {
			t.Errorf("%d calls, body\n%s", len(calls), f.pr.body)
		}
	})
	t.Run("the round runs after green CI in the Fire that pushed, on the checklist the PR opened with", func(t *testing.T) {
		f := newFireFixture(t, labelsConfig)
		f.gh.HandleFunc("POST", pullsPath, func(r githubtest.Request) githubtest.Reply {
			var sent struct{ Body string }
			json.Unmarshal([]byte(r.Body), &sent)
			f.pr.body = sent.Body
			return githubtest.JSON(201, map[string]any{"number": 55, "head": map[string]any{"ref": "feat/issue-20"}})
		})
		f.answer(finished)
		f.verifier.Script(verdicts(nil, passes(finished.Checklist[0]), passes(finished.Checklist[1])))
		f.mustFire(0)
		record := f.record()
		if namesOf(record) != "implement,pre-commit-review,review-correctness,review-spec,verify" || f.labelled() != "AFK:done" || strings.Count(f.pr.body, "- [x] ") != 2 {
			t.Errorf("steps %s, labels %q, body\n%s", namesOf(record), f.labelled(), f.pr.body)
		}
		if calls := strings.Join(f.provider.Calls(), "|"); calls != "down --all|down --all|up --pr 20|smoke|down --pr 20|down --all|up --pr 55|down --pr 55" {
			t.Errorf("the provider was called %s", calls)
		}
	})
	t.Run("no round on red CI, nor on a PR whose review handed it to the reconcile Lane", func(t *testing.T) {
		red := newFireFixture(t, `{"commit_scopes":["a"],"commands":{"install":"x","test":"y"},"pick":{"labels":{}},"rounds":{"pr_watch":1}}`)
		red.ci = [][]map[string]any{{checkRun(2, "unit", "completed", "failure")}}
		red.gh.Handle("GET", "/repos/acme/widgets/actions/jobs/2/logs", githubtest.Text(200, "boom\n"))
		red.answer(finished)
		red.fixer.Script(fixed("echo Hello > greeting.txt", "fix(a): capitalise the greeting"))
		red.mustFire(0)
		threads := newFireFixture(t, labelsConfig)
		threads.answer(finished)
		threads.correctness.Script(found(review.CorrectnessName, realBug))
		threads.mustFire(0)
		for name, f := range map[string]*fireFixture{"red": red, "threads": threads} {
			if verifyOf(f.record()) != nil || strings.Contains(strings.Join(f.pr.comments, "\n"), "### Manual verification") || f.labelled() == "AFK:done" {
				t.Errorf("%s: record %v", name, f.record())
			}
		}
	})
	t.Run("no round while a required check has not reported: no check at all is not green when the Harness requires one", func(t *testing.T) {
		pushed := newFireFixture(t, `{"commit_scopes":["a"],"commands":{"install":"x","test":"y"},"pick":{"labels":{}},"required_checks":["test"]}`)
		pushed.ci = [][]map[string]any{{}}
		pushed.answer(finished)
		pushed.mustFire(0)
		reconciled := newFireFixture(t, `{"commit_scopes":["a"],"commands":{"install":"x","test":"y"},"pick":{"labels":{}},"required_checks":["test"]}`)
		reconciled.ci = [][]map[string]any{{}}
		reconciled.reviewedPR(sayHello)
		reconciled.mustFire(0)
		for name, f := range map[string]*fireFixture{"pushed": pushed, "reconciled": reconciled} {
			if len(f.verifier.Calls()) != 0 || verifyOf(f.record()) != nil || f.labelled() == "AFK:done" || ciOf(f.record())["result"] == "none" {
				t.Errorf("%s: %d Verify calls, labels %q, record %v", name, len(f.verifier.Calls()), f.labelled(), f.record())
			}
		}
	})
	// bootstrap-state: "the round labels AFK:verify-human, posts one comment
	// saying why, and runs no round"
	t.Run("bootstrap-state: AFK:verify-human and one comment saying why, no round", func(t *testing.T) {
		f := newFireFixture(t, `{"commit_scopes":["a"],"commands":{"install":"x","test":"y"},"pick":{"labels":{}},"verification":{}}`)
		f.reviewedPR(sayHello)
		f.mustFire(0)
		v := verifyOf(f.record())
		if len(f.provider.Calls()) != 0 || len(f.verifier.Calls()) != 0 || strings.Join(f.pr.labels, ",") != "AFK:verify-human" || f.labelled() != "" || v["bootstrap"] != true {
			t.Errorf("labels %v, record %v", f.pr.labels, f.record())
		}
		if comments := strings.Join(f.pr.comments, "\n"); strings.Count(comments, "Bootstrap state") != 1 || !strings.Contains(comments, "no hermetic tier") {
			t.Errorf("comments %v", f.pr.comments)
		}
		// Said once: the PR's answer is on it.
		f.mustFire(0)
		if strings.Count(strings.Join(f.pr.comments, "\n"), "Bootstrap state") != 1 {
			t.Errorf("comments %v", f.pr.comments)
		}
	})
	// verify-boot: "round: tour Surface, viewport, named shot, ticked box and
	// the tour in the body"
	t.Run("round: tour Surface, viewport, named shot, ticked box and the tour in the body", func(t *testing.T) {
		f := newFireFixture(t, `{"commit_scopes":["a"],"commands":{"install":"x","test":"y"},"pick":{"labels":{}},
			"surfaces":{"web":{"kind":"browser","url_key":"WEB_URL","paths":["greeting.txt"],"viewport":"390x844"},"cli":{"kind":"cli","url_key":"API_URL","paths":["cmd/"]}}}`)
		f.provider.Script(providertest.Healthy("WEB_URL=http://127.0.0.1:9/\nAPI_URL=http://127.0.0.1:8/\n"))
		// The display is the Host's, probed before it is trusted.
		bin := t.TempDir()
		os.WriteFile(filepath.Join(bin, "xdpyinfo"), []byte("#!/bin/sh\nexit 0\n"), 0o755)
		t.Setenv("PATH", bin+string(os.PathListSeparator)+os.Getenv("PATH"))
		t.Setenv("DISPLAY", ":42")
		f.environ["DISPLAY"] = ":42"
		f.gh.HandleFunc("POST", pullsPath, func(r githubtest.Request) githubtest.Reply {
			var sent struct{ Body string }
			json.Unmarshal([]byte(r.Body), &sent)
			f.pr.body = sent.Body
			return githubtest.JSON(201, map[string]any{"number": 55, "head": map[string]any{"ref": "feat/issue-20"}})
		})
		f.answer(finished)
		f.verifier.Script(verdictsVia([]string{"surface-web"}, []verifier.Shot{{File: "web-01-greeting.png", Shows: "the greeting on a phone"}},
			passes(finished.Checklist[0]), passes(finished.Checklist[1])))
		f.mustFire(0)
		call := f.verifier.Calls()[0]
		mcp, _ := call.Arg("--mcp-config")
		if !strings.Contains(mcp, `"surface-web"`) || !strings.Contains(mcp, `"--viewport-size","390,844"`) || !strings.Contains(mcp, `"DISPLAY":":42"`) || strings.Contains(mcp, "surface-cli") {
			t.Errorf("the Step was handed --mcp-config %s", mcp)
		}
		input := f.verifyInput(t)
		want := []verifier.Surface{{Name: "cli", Kind: "cli", URL: "http://127.0.0.1:8/"}, {Name: "web", Kind: "browser", URL: "http://127.0.0.1:9/", Viewport: "390x844", Server: "surface-web", Tour: true}}
		if got, _ := json.Marshal(input.Surfaces); string(got) != func() string { b, _ := json.Marshal(want); return string(b) }() {
			t.Errorf("the Step was told the Surfaces %s", got)
		}
		if !strings.Contains(f.pr.body, "## Screenshots\n<!-- auto-agent-screenshots -->") || !strings.Contains(f.pr.body, "**web — the greeting on a phone**") ||
			!strings.Contains(f.pr.body, filepath.Join(input.EvidenceDir, "web-01-greeting.png")) || strings.Count(f.pr.body, "- [x] ") != 2 || verifyOf(f.record())["shots"] != 1.0 {
			t.Errorf("the body is\n%s", f.pr.body)
		}
		// The browser's profile is gone with the round.
		if profiles, _ := os.ReadDir(filepath.Join(input.EvidenceDir, "run", "profiles")); len(profiles) != 0 {
			t.Errorf("profiles left behind: %v", profiles)
		}
	})
	t.Run("no display for a UI Surface is an infrastructure error, not a verdict", func(t *testing.T) {
		f := newFireFixture(t, `{"commit_scopes":["a"],"commands":{"install":"x","test":"y"},"pick":{"labels":{}},
			"surfaces":{"web":{"kind":"browser","url_key":"WEB_URL","paths":["greeting.txt"]}}}`)
		// The doctor saw a display when the Fire started; it is gone by the
		// round.
		f.environ["DISPLAY"] = ":42"
		t.Setenv("DISPLAY", "")
		f.reviewedPR(sayHello)
		f.mustFire(0)
		round := f.pr.comments[len(f.pr.comments)-1]
		if len(f.verifier.Calls()) != 0 || !strings.Contains(round, "infrastructure error") || f.labelled() != "" {
			t.Errorf("comments %v", f.pr.comments)
		}
		// The environment that did boot is torn down.
		if calls := f.provider.Calls(); calls[len(calls)-1] != "down --pr 55" {
			t.Errorf("the provider was called %v", calls)
		}
	})
}
