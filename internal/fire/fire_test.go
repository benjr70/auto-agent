// The Fire itself is tested whole, through `run --once`, in internal/cli.

func TestCommitMessage(t *testing.T) {
	tests := []struct {
		name   string
		result implement.Result
		want   string
	}{
		{"the Step's message gains the line that closes the ticket", implement.Result{Finished: true, CommitMessage: "feat(a): x\n\nBody.\n"}, "feat(a): x\n\nBody.\n\nCloses #7\n"},
		{"a message that already closes the ticket is not given a second line", implement.Result{Finished: true, CommitMessage: "feat(a): x\n\ncloses #7"}, "feat(a): x\n\ncloses #7\n"},
		{"closing another ticket does not count", implement.Result{Finished: true, CommitMessage: "feat(a): x\n\nCloses #70"}, "feat(a): x\n\nCloses #70\n\nCloses #7\n"},
		{"unfinished work is committed as work in progress, with the summary", implement.Result{Summary: " half \n", CommitMessage: "feat(a): x"}, "wip: partial work on #7\n\nhalf\n"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := commitMessage(tt.result, 7); got != tt.want {
				t.Errorf("message = %q, want %q", got, tt.want)
			}
		})
	}
}

func TestPullRequestBody(t *testing.T) {
	t.Run("the PR body has the required sections, in order, and the Step's checklist items", func(t *testing.T) {
		body := PullRequestBody(github.Issue{Number: 7, Title: "Tracer"},
			implement.Result{Summary: " Did it. ", Checklist: []string{"first", " second "}}, time.Date(2026, 10, 12, 9, 30, 0, 0, time.FixedZone("EST", -5*3600)))
		at := 0
		for _, want := range []string{"## Summary\n\nDid it.\n", "## Closes\n\nCloses #7 — Tracer\n", "## Smoke\n\n`smoke: SKIPPED", "## Manual verification\n\n- [ ] first\n- [ ] second\n", "Generated by `auto-agent` at 2026-10-12T14:30:00Z\n"} {
			i := strings.Index(body[at:], want)
			if i < 0 {
				t.Fatalf("the body lacks %q after byte %d:\n%s", want, at, body)
			}
			at += i
		}
	})
}
